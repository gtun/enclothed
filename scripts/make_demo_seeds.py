"""Write the two synthetic demo wardrobes in seeds/: menswear + unisex, and womenswear + unisex.

Each archetype below is one kind of garment, expanded into one row per color. Unisex archetypes
are split between the two seeds (even-numbered colors to menswear, odd to womenswear), so the
seeds share kinds of pieces but no rows. Archetypes in the same `kit` with the same primary color
become a set (a suit, a setup, a sweatsuit).

Run from the repo root:  uv run python scripts/make_demo_seeds.py
Every row is validated against Garment, so a typo fails here rather than at load time.
"""
