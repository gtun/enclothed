def trim(seed: dict, target: int) -> dict:
    """Cut to target: from the category furthest above its share, drop the last row of its most common subcategory.
    That spreads the cuts across kinds of garment instead of taking whole archetypes. Sets stay whole."""
    garments = seed["garments"]
    kit_ids = {i for s in seed["sets"] for i in s["garment_ids"]}
    start = Counter(g["garment"]["category"] for g in garments)
    while len(garments) > target:
        candidates = [g for g in garments if g["source_id"] not in kit_ids]
        now = Counter(g["garment"]["category"] for g in garments)
        biggest = max(now, key=lambda c: now[c] / start[c])   # cut each category in proportion
        in_biggest = [g for g in candidates if g["garment"]["category"] == biggest]
        busiest = Counter(g["garment"]["subcategory"] for g in in_biggest).most_common(1)[0][0]
        garments.remove([g for g in in_biggest if g["garment"]["subcategory"] == busiest][-1])
    return seed


