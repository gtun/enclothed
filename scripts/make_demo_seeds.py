def materials(text: str) -> list[dict]:
    """ "cotton 100" or "shell: nylon 100; lining: polyester 100" -> Garment.materials."""
    parts = []
    for chunk in text.split(";"):
        part, _, fibers = chunk.rpartition(":")
        parts.append({
            "part": part.strip() or None,
            "fibers": [{"fiber": f.rsplit(" ", 1)[0].strip(), "percent": int(f.rsplit(" ", 1)[1])} for f in fibers.split(",")],
        })
    return parts


def A(cat, sub, fabric, mat, form, warm, fit, shape, hem, sleeve, weight, sheen, stmt, tags, note, colors,
      brands="", origins="", pattern="", kit=None):
    """One clothing archetype. colors: "navy, white|navy" (primary|secondary, accents after +)."""
    return dict(cat=cat, sub=sub, fabric=fabric, mat=mat, form=form, warm=warm, fit=fit, shape=shape, hem=hem,
                sleeve=sleeve, weight=weight, sheen=sheen, stmt=stmt, tags=tags, note=note, colors=colors,
                brands=brands, origins=origins, pattern=pattern, kit=kit)


def S(sub, fabric, mat, form, warm, sheen, stmt, tags, note, colors, brands="", origins="", pattern=""):
    """A shoe archetype: no fit, shape, hem, sleeve or fabric weight."""
    return A("shoes", sub, fabric, mat, form, warm, None, None, None, None, None, sheen, stmt, tags, note, colors, brands, origins, pattern)


def X(sub, fabric, mat, form, warm, sheen, stmt, tags, note, colors, brands="", origins="", pattern=""):
    """An accessory archetype."""
    return A("accessory", sub, fabric, mat, form, warm, None, None, None, None, None, sheen, stmt, tags, note, colors, brands, origins, pattern)


def split_list(text: str) -> list[str]:
    return [t.strip() for t in text.split(",") if t.strip()]


def parse_color(spec: str) -> tuple[str, list[str], list[str]]:
    spec, _, accents = spec.partition("+")
    primary, _, secondary = spec.partition("|")
    return primary.strip(), split_list(secondary.replace("/", ",")), split_list(accents.replace("/", ","))


def phrase(primary: str, secondary: list[str]) -> str:
    return " and ".join([primary] + secondary) if secondary else primary


def expand(archetypes: list[dict], take=slice(None)) -> list[dict]:
    rows = []
    for arch in archetypes:
        brands = cycle(split_list(arch["brands"]) or [None])
        origins = cycle(split_list(arch["origins"]) or [None])
        for spec in split_list(arch["colors"])[take]:
            primary, secondary, accents = parse_color(spec)
            garment = {
                "category": arch["cat"], "subcategory": arch["sub"],
                "primary_color": primary, "secondary_colors": secondary, "accent_colors": accents,
                "formality": arch["form"], "warmth": arch["warm"],
                "materials": materials(arch["mat"]) if arch["mat"] else [],
                "pattern": arch["pattern"] or None,
                "country_of_origin": next(origins), "brand": next(brands),
                "style_tags": split_list(arch["tags"]),
                "styling_notes": arch["note"].format(c=phrase(primary, secondary)),
                "fit": arch["fit"], "sheen": arch["sheen"], "fabric_type": arch["fabric"],
                "shape": arch["shape"], "hem": arch["hem"], "fabric_weight": arch["weight"],
                "sleeve": arch["sleeve"], "statement": arch["stmt"],
            }
            Garment.model_validate(garment)   # fail loudly on a bad value
            rows.append({"garment": garment, "kit": arch["kit"]})
    return rows


def build(name: str, own: list[dict], unisex_take: slice) -> dict:
    rows = expand(own) + expand(UNISEX, unisex_take)
    garments, kits = [], {}
    for source_id, row in enumerate(rows, start=1):
        garments.append({"source_id": source_id, "garment": row["garment"]})
        if row["kit"]:
            kits.setdefault((row["kit"], row["garment"]["primary_color"]), []).append(source_id)
    sets = [{"name": f"{color} {kit}", "garment_ids": ids} for (kit, color), ids in kits.items() if len(ids) > 1]
    counts = Counter(g["garment"]["category"] for g in garments)
    print(f"{name}: {len(garments)} garments, {len(sets)} sets, {dict(sorted(counts.items()))}")
    return {"garments": garments, "sets": sets, "outfits": []}


